import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Android owns the native built-in palette. Keep the Swift projection exact.
const root = new URL("../", import.meta.url);
const design = readFileSync(
  new URL("apps/android/app/src/main/java/ai/openclaw/app/ui/design/ClawTheme.kt", root),
  "utf8",
);
const families = readFileSync(
  new URL("apps/android/app/src/main/java/ai/openclaw/app/AppearanceThemeFamily.kt", root),
  "utf8",
);
const columns = [
  "canvas",
  "surface",
  "raised",
  "pressed",
  "accent",
  "border",
  "borderStrong",
  "text",
  "muted",
  "primary",
  "primaryText",
  "secondary",
];
const rows = [];
for (const match of families.matchAll(/^ {2}(\w+)\("(\w+)", "([^"]+)"/gm)) {
  const [, name, id, label] = match;
  const values = {};
  for (const mode of ["dark", "light"]) {
    if (id === "claw") {
      const block = design
        .split("private val Claw" + (mode === "dark" ? "Dark" : "Light") + "Colors =")[1]
        ?.split("private ")[0];
      const aliases = { raised: "surfaceRaised", pressed: "surfacePressed", muted: "textMuted" };
      values[mode] = columns.map((column) => {
        const value = block?.match(
          new RegExp("\\b" + (aliases[column] ?? column) + " = Color\\(0x([0-9A-F]{8})\\)"),
        )?.[1];
        if (!value) {
          throw new Error("Missing Claw " + mode + " " + column);
        }
        return value;
      });
    } else {
      const block = design
        .split("AppearanceThemeFamily." + name + " to")[1]
        ?.split("AppearanceThemeFamily.")[0];
      const tuple = block?.match(new RegExp(mode + " = WebThemePalette\\(([^)]+)\\)"))?.[1];
      values[mode] = [...(tuple ?? "").matchAll(/0x([0-9A-F]{8})/g)].map((value) => value[1]);
    }
    if (values[mode].length !== columns.length) {
      throw new Error("Invalid palette " + id + " " + mode);
    }
  }
  rows.push({
    id,
    label: label.replace(/\\u([0-9a-f]{4})/gi, (_, hex) =>
      String.fromCharCode(Number.parseInt(hex, 16)),
    ),
    values,
  });
}
if (rows.length !== 11) {
  throw new Error("Expected 11 Android theme families");
}
const output =
  "// Generated by scripts/ios-theme-palettes.mjs from Android ClawTheme.kt. Do not edit.\n" +
  "import Foundation\n\nenum AppThemeFamily: String, CaseIterable, Identifiable, Sendable {\n" +
  rows.map(({ id }) => "    case " + id).join("\n") +
  "\n\n    var id: String { self.rawValue }\n\n    var displayName: String {\n        switch self {\n" +
  rows.map(({ id, label }) => "        case ." + id + ': "' + label + '"').join("\n") +
  "\n        }\n    }\n\n    func seed(dark: Bool) -> AppThemePaletteSeed {\n        switch (self, dark) {\n" +
  rows
    .flatMap(({ id, values }) =>
      ["dark", "light"].map(
        (mode) =>
          "        case (." +
          id +
          ", " +
          (mode === "dark") +
          "):\n            AppThemePaletteSeed(\n" +
          columns
            .map(
              (column, index) =>
                "                " +
                column +
                ": 0x" +
                values[mode][index] +
                (index === columns.length - 1 ? ")" : ","),
            )
            .join("\n"),
      ),
    )
    .join("\n") +
  "\n        }\n    }\n}\n";
const path = new URL("apps/ios/Sources/Design/AppThemePalettes.generated.swift", root);
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output) {
    throw new Error("iOS palettes are stale; run pnpm ios:themes:gen");
  }
} else {
  writeFileSync(fileURLToPath(path), output);
}
