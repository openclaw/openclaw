import fs from "node:fs/promises";

// The parser table includes the documented directives, shared execution/resource
// controls, and accepted legacy aliases. Keep section membership from upstream.
const source =
  "https://raw.githubusercontent.com/systemd/systemd/v260/src/core/load-fragment-gperf.gperf.in";
const response = await fetch(source);
if (!response.ok) {
  throw new Error(`Could not read systemd directives: HTTP ${response.status}`);
}
const table = await response.text();
const directives = new Set(
  [...table.matchAll(/^(?:Unit|Service|Install)\.\w+(?=,)/gm)].map(([key]) => key),
);
for (const [, macro] of table.matchAll(/\{\{ (\w+)\('Service'\) \}\}/g)) {
  const body = table.match(
    new RegExp(`\\{%[- ]*macro ${macro}\\(type\\).*?%\\}(.*?)\\{%[- ]*endmacro`, "s"),
  )?.[1];
  if (!body) {
    throw new Error(`Missing systemd directive macro: ${macro}`);
  }
  for (const [, key] of body.matchAll(/^\{\{type\}\}\.(\w+)(?=,)/gm)) {
    directives.add(`Service.${key}`);
  }
}
if (
  !["Unit.OnFailure", "Service.CPUWeight", "Install.WantedBy"].every((key) => directives.has(key))
) {
  throw new Error("Incomplete systemd directive table");
}
const lines = [];
for (const key of [...directives].toSorted()) {
  if (!lines.length || lines.at(-1).length + key.length > 96) {
    lines.push(key);
  } else {
    lines[lines.length - 1] += ` ${key}`;
  }
}
await fs.writeFile(
  new URL("../src/daemon/systemd-directives.ts", import.meta.url),
  `// Generated by node scripts/generate-systemd-directives.mjs; do not edit.\n// Source: ${source}\nexport const SYSTEMD_DIRECTIVES = new Set(\n  \`\n${lines.join("\n")}\n\`\n    .trim()\n    .split(/\\s+/u),\n);\n`,
);
