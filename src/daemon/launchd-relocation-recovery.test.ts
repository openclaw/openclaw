    await fs.writeFile(f.canonical, f.original);
    await fs.unlink(f.former);
    await fs.symlink(f.canonical, f.former);
    const foreign = path.join(f.args.env.HOME, "operator-definition");
    await fs.writeFile(foreign, "operator bytes");
    const readlink = fs.readlink;
    let replaced = false;
    vi.spyOn(fs, "readlink").mockImplementation(async (...args) => {
      const target = await readlink(...args);
      if (args[0] === f.former && !replaced) {
        replaced = true;
        await fs.unlink(f.former);
        await fs.symlink(foreign, f.former);
      }
      return target;
    });
    await expect(installLaunchAgent(f.args)).rejects.toThrow(
      "registration changed during inspection",
    );
