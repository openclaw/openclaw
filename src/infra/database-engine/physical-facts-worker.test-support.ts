import { channel } from "node:diagnostics_channel";
import { parentPort, threadId, workerData } from "node:worker_threads";
import { openNodeSqliteDatabase } from "../node-sqlite.js";
import { PostgresSyncConnection } from "../postgres-sync/connection.js";
import {
  installSqliteDatabaseAdmissions,
  publishSqliteDatabaseSchemaChange,
  type SqliteDatabaseAdmissions,
} from "../sqlite-database-admission.js";
import { admitSqliteSchema, getAdmittedSqliteSchemaFacts } from "../sqlite-schema-facts.js";
import type { PhysicalFactsTestResult } from "./physical-facts-runtime.test-support.js";
import { admitPostgresPhysicalFacts } from "./physical-facts.js";

const input: {
  connection: string;
  namespace: string;
  storeId: string;
  path: string;
  admissions: SqliteDatabaseAdmissions;
} = workerData;
if (!parentPort) {
  throw new Error("Catalog fixture requires a worker");
}
const port = parentPort;
const failure = (operation: () => unknown): string => {
  try {
    operation();
    return "";
  } catch (error) {
    return error instanceof Error ? error.message : String(error);
  }
};
try {
  installSqliteDatabaseAdmissions(input.admissions);
  const anchor = openNodeSqliteDatabase(input.path);
  admitSqliteSchema(anchor);
  try {
    const db = new PostgresSyncConnection(input.connection, input.namespace, anchor, input.storeId);
    let catalogReads = 0;
    const statements = channel("openclaw.database.statement");
    const observe = (message: unknown) => {
      if (
        message &&
        typeof message === "object" &&
        "sql" in message &&
        typeof message.sql === "string" &&
        message.sql.startsWith("WITH captured")
      ) {
        catalogReads++;
      }
    };
    statements.subscribe(observe);
    let result: PhysicalFactsTestResult;
    try {
      db.exec(`CREATE SCHEMA "${input.namespace}";
        CREATE TABLE openclaw_schema_meta (store TEXT PRIMARY KEY, version BIGINT NOT NULL, store_id TEXT NOT NULL);
        CREATE TABLE parents (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL DEFAULT 'seed' CHECK (length(name) > 0));
        CREATE TABLE children (id BIGINT PRIMARY KEY, parent_id BIGINT REFERENCES parents(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED);
        CREATE INDEX child_parent ON children(parent_id DESC NULLS LAST) WHERE parent_id > 0;`);
      db.prepare("INSERT INTO openclaw_schema_meta VALUES (?, ?, ?)").run(
        "fixture",
        7,
        input.storeId,
      );
      const params = {
        anchor,
        db,
        namespace: input.namespace,
        storeId: input.storeId,
        store: "fixture",
        version: 7,
      };
      const facts = admitPostgresPhysicalFacts(params);
      const counts = [catalogReads];
      const nativeHasParents = getAdmittedSqliteSchemaFacts(anchor)?.tables.has("parents") ?? false;
      db.runTransaction(() => db.prepare("INSERT INTO parents (name) VALUES (?)").run("written"));
      const writtenName = db.prepare("SELECT name FROM parents").get()?.name;
      const reusedAdmissionId = admitPostgresPhysicalFacts(params).admissionId;
      counts.push(catalogReads);
      db.exec("UPDATE openclaw_schema_meta SET version = 8");
      publishSqliteDatabaseSchemaChange(anchor);
      const versionError = failure(() => admitPostgresPhysicalFacts(params));
      counts.push(catalogReads);
      db.exec("UPDATE openclaw_schema_meta SET version = 7");
      const renewedAdmissionId = admitPostgresPhysicalFacts(params).admissionId;
      counts.push(catalogReads);
      db.exec("ALTER TABLE openclaw_schema_meta RENAME TO missing_metadata");
      publishSqliteDatabaseSchemaChange(anchor);
      const missingError = failure(() => admitPostgresPhysicalFacts(params));
      result = {
        threadId,
        facts,
        catalogReads: counts,
        nativeHasParents,
        writtenName,
        reusedAdmissionId,
        renewedAdmissionId,
        versionError,
        missingError,
      };
    } finally {
      statements.unsubscribe(observe);
      try {
        db.exec(`DROP SCHEMA IF EXISTS "${input.namespace}" CASCADE`);
      } finally {
        db.close();
      }
    }
    port.postMessage(result);
  } finally {
    anchor.close();
  }
} catch (error) {
  port.postMessage({ error: error instanceof Error ? error.message : String(error) });
} finally {
  port.close();
}
