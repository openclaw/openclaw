// Generated index DDL quotes identifiers and parenthesizes every key expression.
const generatedIndexes =
  /CREATE (?:UNIQUE )?INDEX ("(?:[^"]|"")+") ON ("(?:[^"]|"")+") (?:'(?:[^']|'')*'|"(?:[^"]|"")*"|[^;'"])*;/g;
const orderedKeys = /'(?:[^']|'')*'|"(?:[^"]|"")*"|\) (ASC|DESC)(?=,|\))/g;
type HistoricalOrdering = "sqlite" | "schema-nullability";

/** Restore a predecessor's index policy; generated table DDL owns column nullability. */
export function withLegacyPostgresIndexOrdering(
  sql: string,
  policy: HistoricalOrdering = "sqlite",
  schemaSql = sql,
): string {
  const nullable = new Map<string, Set<string>>();
  if (policy === "schema-nullability") {
    for (const [, table, body] of schemaSql.matchAll(
      /CREATE TABLE ("(?:[^"]|"")+") \(\n([\s\S]*?)\n\);/g,
    )) {
      nullable.set(
        table!,
        new Set(
          [
            ...body!.matchAll(
              /^ {2}("(?:[^"]|"")+") (?:text|bigint|bytea|double precision)([^\n]*)/gm,
            ),
          ]
            .filter(
              (match) =>
                !/\bNOT NULL\b/.test(
                  match[2]!
                    .replace("GENERATED BY DEFAULT AS IDENTITY", "")
                    .split(/\bDEFAULT\b/)[0]!,
                ),
            )
            .map(([, column]) => column!),
        ),
      );
    }
  }
  return sql.replace(generatedIndexes, (index, _name: string, table: string) => {
    if (policy === "schema-nullability") {
      return index.replace(
        /'(?:[^']|'')*'|"(?:[^"]|"")*"|\(("(?:[^"]|"")+")\) (ASC|DESC)(?=,|\))/g,
        (key: string, column: string | undefined, order: string | undefined) =>
          column && nullable.get(table)?.has(column)
            ? `${key} NULLS ${order === "DESC" ? "LAST" : "FIRST"}`
            : key,
      );
    }
    return index.replace(orderedKeys, (key: string, order: string | undefined) =>
      order ? `${key} NULLS ${order === "DESC" ? "LAST" : "FIRST"}` : key,
    );
  });
}

/** The schema owner runs this under its existing versioned admission transaction. */
export function postgresIndexOrderingMigration(
  sql: string,
  policy: HistoricalOrdering = "sqlite",
): string {
  const previous = withLegacyPostgresIndexOrdering(sql, policy);
  const previousIndexes = new Map(
    [...previous.matchAll(generatedIndexes)].map(([index, name]) => [name, index]),
  );
  return [...sql.matchAll(generatedIndexes)]
    .filter(([index, name]) => previousIndexes.get(name) !== index)
    .map(
      ([index, name, table]) => `DO $index_order$
BEGIN
  IF to_regclass('${table!.replaceAll("'", "''")}') IS NOT NULL THEN
    DROP INDEX ${name};
    ${index}
  END IF;
END $index_order$;`,
    )
    .join("\n");
}
