export async function isGeneratedTemplateContent(
  fileName: string,
  content: string,
): Promise<boolean> {
  let template: string | undefined;
  try {
    template = await loadWorkspaceTemplate(fileName);
  } catch (error) {
    if (!(error instanceof MissingWorkspaceTemplateError)) {
      throw error;
    }
  }
  return (
    content === template ||
    RETIRED_GENERATED_TEMPLATE_SHA256[fileName]?.includes(sha256Hex(content)) === true
  );
}

export async function fileDiffersFromTemplate(
  dir: string,
  fileName: string,
  generatedHash?: string,
): Promise<boolean> {
  try {
    return await retryWorkspaceRead(async () => {
      const content = await fs.readFile(path.join(dir, fileName), "utf-8");
      return (
        (!generatedHash || sha256Hex(content) !== generatedHash) &&
        !(await isGeneratedTemplateContent(fileName, content))
      );
    });
  } catch (err) {
    if (hasNodeErrorCode(err, "ENOENT")) {
      return false;
    }
    throw err;
  }
}

export function loadWorkspaceTemplate(name: string): Promise<string> {
  return getOrCreatePromise(
    workspaceTemplateCache,
    name,
    async () => {
      const templateDirs = await resolveWorkspaceTemplateSearchDirs();
      const triedPaths: string[] = [];
      for (const templateDir of templateDirs) {
        const templatePath = path.join(templateDir, name);
        triedPaths.push(templatePath);
        try {
          const content = await fs.readFile(templatePath, "utf-8");
          return extractFrontmatterBlock(content)?.body.replace(/^\s+/, "") ?? content;
        } catch (error) {
          if (!hasNodeErrorCode(error, "ENOENT")) {
            throw error;
          }
        }
      }
      throw new MissingWorkspaceTemplateError(
        `Missing workspace template: ${name} (${triedPaths.join(", ")}). Check that workspace templates are packaged.`,
      );
    },
    { cacheRejections: false },
  );
}
