/**
 * Compose overlay for a split Gateway + teammate worker install.
 */
import { DEFAULT_FIRECRACKER_OCI_RUNTIME, type TeammateBackend } from "./profile.js";

export type TeammateComposeParams = {
  backend: TeammateBackend;
  homeDir: string;
};

/** Generate a docker-compose overlay that keeps exec off the gateway host. */
export function renderTeammateComposeOverlay(params: TeammateComposeParams): string {
  const runtimeLine =
    params.backend === "firecracker"
      ? `\n      # Firecracker/Kata OCI runtime (requires a configured container runtime).\n      # OPENCLAW_TEAMMATE_RUNTIME: ${DEFAULT_FIRECRACKER_OCI_RUNTIME}\n`
      : "";
  return `# OpenClaw teammate overlay — Gateway stays cheap; the worker is the computer.
# Generated by: openclaw init --mode teammate
#
# Upgrade note:
# - Gateway-is-the-computer (typical Coolify / host-exec install): stop using
#   tools.exec.host=gateway. Point sandbox + browser + computer at this worker.
# - True split: this file. Gateway process on a VPS; durable /home/bot lives here.
#
# Do not exec on the gateway host. Confirm with:
#   openclaw sandbox explain --json
#   openclaw security audit

services:
  openclaw-gateway:
    environment:
      OPENCLAW_TEAMMATE_HOME: ${params.homeDir}
    volumes:
      - ${params.homeDir}:${params.homeDir}
    # Gateway may talk to Docker to start the shared worker. Agent exec stays
    # inside that worker (tools.exec.host=sandbox), never on this process.
${runtimeLine}
volumes:
  # Host path is the durable worker disk (files, browser profile, logins).
  # Named here so operators can backup ${params.homeDir} independently of Gateway state.
`;
}
