// Keep authored shared guidance in one place while making each host-exported
// skill directory self-contained. No symlinks or references outside its bundle.
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../skills/", import.meta.url));
const check = process.argv.includes("--check");
// Small topic references that skills link on demand. They link only to each
// other and the worked example, so every skill receives the complete set.
const topics = [
  "setup.md",
  "sources.md",
  "identity.md",
  "publish.md",
  "recovery.md",
  "assertions.md",
  "profiles.md",
  "verify.md",
  "writing.md",
  "meeting-entity-example.md",
];
for (const name of (await readdir(root)).filter((entry) => entry.startsWith("knowledge-"))) {
  // Automation setup routes to ingestion skills; it does not publish content.
  if (name === "knowledge-automation") {
    continue;
  }
  const files = [
    ...(name === "knowledge-recall" ? ["conventions.md"] : ["conventions.md", "publication.md"]),
    ...topics,
  ];
  for (const file of files) {
    const source = await readFile(path.join(root, "shared", file), "utf8");
    const content =
      "<!-- Generated by scripts/sync-skill-references.mjs; edit skills/shared/" +
      file +
      ". -->\n\n" +
      (name === "knowledge-recall"
        ? source.replace("For writes, also read\n[publication.md](publication.md). ", "")
        : source);
    const target = path.join(root, name, "references", file);
    if (check) {
      if ((await readFile(target, "utf8").catch(() => "")) !== content) {
        throw new Error(
          `Stale skill reference: ${name}/references/${file}; run node extensions/knowledge/scripts/sync-skill-references.mjs`,
        );
      }
    } else {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, content);
    }
  }
}
