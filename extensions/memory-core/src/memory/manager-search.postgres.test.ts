function createFixture(
  root: string,
  name: string,
  dsn: string,
  tokenizer: "unicode61" | "trigram" = "unicode61",
  installUnaccent = false,
) {
  const anchor: DatabaseSync = openNodeSqliteDatabase(path.join(root, `${name}.sqlite`));
  let database: EngineConnection;
  let backend: ReturnType<typeof bindSqliteWorkerBackend>;
  const pg = () => {
    if (!isPostgresSqlConnection(database)) {
      throw new Error("Expected PostgreSQL memory search fixture");
    }
    return database;
  };
  const open = () => {
    database = openEngineStore({
      anchor,
      input: { connection: dsn, schemaPrefix: "memory_search_test" },
      schema: {
        id: "memory_search",
        version: 1,
        sqlite: "",
        postgres: schema,
        postgresVectorSearchVersion: 2,
      },
      openSqlite: () => {
        throw new Error("Unexpected SQLite memory search fixture");
      },
      prepareAnchor: () => {},
      inspectSqlite: () => ({ hasExistingData: false, hasEngineAnchor: false }),
    });
    backend = bindSqliteWorkerBackend(
      { kind: "agent" },
      {
        database,
        databasePath: path.join(root, `${name}.sqlite`),
        admit() {},
        admitSearchExtensions(definitions) {
          pg().runTransaction(() => {
            for (const [extension, definition] of Object.entries(definitions)) {
              admitStoreSearch(database, definition, { extension });
            }
          });
        },
      },
    );
    if (installUnaccent) {
      pg().exec("CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public");
    }
    pg().runTransaction(() =>
      admitStoreSearch(database, memoryTextSearchSchema(tokenizer), { extension: "memory.text" }),
    );
  };
  open();
  return {
    pg,
    ensureVector: () => backend.execute({ type: "vector.ensure", input: { dimensions: 3, state } }),
    publish(
      sourceName: string,
      text: string,
      embedding: number[],
      options: { model?: string; source?: MemorySource; path?: string } = {},
    ) {
      const input: MemorySourceIndexReplacement = {
        ...(options.source === "sessions"
          ? { source: "sessions", agentId: "fixture", sessionId: sourceName }
          : { source: "memory" }),
        entry: {
          path: options.path ?? `memory/${sourceName}.md`,
          hash: sourceName,
          mtimeMs: 100,
          size: text.length,
        },
        chunks: [
          {
            startLine: 1,
            endLine: 1,
            hash: sourceName,
            text,
            importance: null,
            triggers: null,
            projectKey: null,
          },
        ],
        embeddings: [embedding],
        model: options.model ?? "fixture",
        now: 100,
        vectorReady: embedding.length > 0,
      };
      const inline = memoryPublicationInline(input);
      if (!inline) {
        throw new Error("Expected bounded inline memory search fixture");
      }
      expect(
        backend.execute({
          type: "source.replace.inline",
          input: { ...inline, state: embedding.length ? state : keywordState },
        }),
      ).toMatchObject({ ok: true, value: true });
    },
    vector: (query = vectorQuery()) =>
      admitted(() => ({
        pending: executeMemorySearchWorkerQuery(database, { kind: "vector", query }),
      })).pending,
    keyword: (query: MemoryKeywordWorkerQuery) =>
      admitted(() => ({
        pending: executeMemorySearchWorkerQuery(database, { kind: "keyword", query }),
      })).pending,
    restart() {
      backend.close();
      database.close();
      open();
    },
    close() {
      backend?.close();
      if (database?.isOpen) {
        const namespace = String(pg().prepare("SELECT current_schema() AS name").get()!.name);
        pg().exec(`DROP SCHEMA "${namespace}" CASCADE`);
        database.close();
      }
      anchor.close();
    },
  };
}

