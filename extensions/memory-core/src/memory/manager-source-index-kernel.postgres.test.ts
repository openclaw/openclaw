import { channel } from "node:diagnostics_channel";
import fs from "node:fs";
import path from "node:path";
import { getEnvironmentData, threadId } from "node:worker_threads";
import {
  admitStoreSearch,
  openEngineStore,
  withEngineStoreAdmission,
  type EngineConnection,
} from "openclaw/plugin-sdk/database-engine-worker-runtime";
import { isPostgresSqlConnection } from "openclaw/plugin-sdk/memory-core-host-engine-storage";
import { openNodeSqliteDatabase } from "openclaw/plugin-sdk/sqlite-worker-runtime";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { memoryTextSearchSchema, memoryVectorSearchSchema } from "./manager-search-schema.js";
import {
  MemorySourceIndexKernel,
  readMemorySourceChunks,
  type MemorySourceIndexReplacement,
} from "./manager-source-index-kernel.js";
import { markMemoryVectorIndexClean } from "./manager-vector-rebuild-state.js";

const configured = getEnvironmentData("openclaw.test.workboard.connection");
const connection = typeof configured === "string" ? configured : undefined;
const sourceSchema = `
CREATE TABLE memory_index_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path TEXT NOT NULL, source TEXT NOT NULL, hash TEXT NOT NULL,
  mtime DOUBLE PRECISION NOT NULL, size BIGINT NOT NULL, UNIQUE(path, source)
);
CREATE TABLE memory_index_chunks (
  chunk_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id TEXT NOT NULL UNIQUE, path TEXT NOT NULL, source TEXT NOT NULL,
  start_line BIGINT NOT NULL, end_line BIGINT NOT NULL, hash TEXT NOT NULL,
  model TEXT NOT NULL, text TEXT NOT NULL, embedding BYTEA NOT NULL, updated_at BIGINT NOT NULL
);
CREATE TABLE memory_index_chunk_recall_metadata (
  chunk_id TEXT PRIMARY KEY REFERENCES memory_index_chunks(id) ON DELETE CASCADE,
  importance BIGINT, triggers TEXT, project_key TEXT
);
CREATE TABLE memory_index_chunk_provenance (
  chunk_id TEXT PRIMARY KEY REFERENCES memory_index_chunks(id) ON DELETE CASCADE,
  origin_class TEXT NOT NULL, session_kind TEXT NOT NULL,
  observed_at BIGINT NOT NULL, supersedes_key TEXT
);
CREATE TABLE memory_index_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
`;

describe.skipIf(!connection)("PostgreSQL memory source indexing", () => {
  let root: string;
  let anchor: ReturnType<typeof openNodeSqliteDatabase>;
  let db: EngineConnection;
  let namespace: string;
  const state = {
    vector: { enabled: true, available: true },
    fts: { enabled: true, available: true },
    hasVectorTable: true,
  };

  beforeAll(() => {
    expect(threadId, "Admission stays in the suite's application process").toBe(0);
    const artifacts = path.join(process.cwd(), ".artifacts");
    fs.mkdirSync(artifacts, { recursive: true });
    root = fs.mkdtempSync(path.join(artifacts, "memory-source-postgres-"));
    anchor = openNodeSqliteDatabase(path.join(root, "anchor.sqlite"));
    db = withEngineStoreAdmission(() => {
      const opened = openEngineStore({
        anchor,
        input: { connection: connection!, schemaPrefix: "memory_source_test" },
        schema: { id: "memory_source", version: 1, sqlite: "", postgres: sourceSchema },
        openSqlite: () => {
          throw new Error("Unexpected SQLite bootstrap");
        },
        prepareAnchor: () => {},
        inspectSqlite: () => ({ hasExistingData: false, hasEngineAnchor: false }),
      });
      admitStoreSearch(opened, memoryTextSearchSchema("unicode61"), { extension: "memory.text" });
      admitStoreSearch(opened, memoryVectorSearchSchema(3), { extension: "memory.vector" });
      namespace = String(opened.prepare("SELECT current_schema() AS namespace").get()!.namespace);
      return opened;
    });
  });

  afterAll(() => {
    withEngineStoreAdmission(() => {
      if (db && isPostgresSqlConnection(db)) {
        db.exec(`DROP SCHEMA "${namespace.replaceAll('"', '""')}" CASCADE`);
        db.close();
      }
      anchor?.close();
    });
    if (root) {
      fs.rmSync(root, { recursive: true, force: true });
    }
  });

  it("replaces 129 rows and rolls back canonical and derived rows", () => {
    withEngineStoreAdmission(() => {
      if (!isPostgresSqlConnection(db)) {
        throw new Error("Expected PostgreSQL");
      }
      const value: MemorySourceIndexReplacement = {
        source: "memory",
        entry: { path: "memory/batch.md", hash: "first", mtimeMs: 100.25, size: 129 },
        model: "test-model",
        now: 100,
        vectorReady: true,
        embeddings: Array.from({ length: 129 }, () => [1, 0, 0]),
        chunks: Array.from({ length: 129 }, (_, index) => ({
          startLine: index + 1,
          endLine: index + 1,
          hash: `chunk-${index}`,
          text: `indexedword ${index}`,
          importance: 7,
          triggers: null,
          projectKey: null,
        })),
      };
      const write = () =>
        new MemorySourceIndexKernel(db, state).replaceRows(
          value,
          value.chunks.map((chunk, index) => ({ chunk, embedding: value.embeddings[index]! })),
        );
      db.runTransaction(() => {
        write();
        markMemoryVectorIndexClean(db);
      });
      const before = db
        .prepare("SELECT id, embedding::text FROM memory_index_chunks_vec ORDER BY id")
        .all();
      expect(before).toHaveLength(129);
      db.exec(`CREATE TEMP TABLE projection_changes (id TEXT);
        CREATE FUNCTION pg_temp.record_projection_change() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN INSERT INTO projection_changes VALUES (coalesce(NEW.id, OLD.id)); RETURN NULL; END $$;
        CREATE TRIGGER record_projection_change AFTER INSERT OR UPDATE OR DELETE
        ON memory_index_chunks_vec FOR EACH ROW EXECUTE FUNCTION pg_temp.record_projection_change()`);
      const statements: string[] = [];
      const events = channel("openclaw.database.statement");
      const observe = (event: unknown) => {
        if (
          event &&
          typeof event === "object" &&
          "engine" in event &&
          event.engine === "postgres" &&
          "sql" in event &&
          typeof event.sql === "string"
        ) {
          statements.push(event.sql);
        }
      };
      events.subscribe(observe);
      try {
        value.entry.hash = "second";
        value.now = 200;
        db.runTransaction(write);
      } finally {
        events.unsubscribe(observe);
      }
      expect(
        statements.every((statement) => [...statement.matchAll(/\$\d+/g)].length < 65_535),
      ).toBe(true);
      expect(
        db.prepare("SELECT id, embedding::text FROM memory_index_chunks_vec ORDER BY id").all(),
      ).toEqual(before);
      expect(db.prepare("SELECT id FROM projection_changes").all()).toEqual([]);
      expect(readMemorySourceChunks(db, "memory", value.entry.path)).toHaveLength(129);
      const database = db;
      expect(() =>
        database.runTransaction(() => {
          value.chunks = value.chunks.slice(0, 1);
          value.embeddings = [[0, 1, 0]];
          write();
          expect(db.prepare("SELECT id FROM projection_changes").all().length).toBeGreaterThan(0);
          throw new Error("rollback source fixture");
        }),
      ).toThrow("rollback source fixture");
      expect(
        db.prepare("SELECT id, embedding::text FROM memory_index_chunks_vec ORDER BY id").all(),
      ).toEqual(before);
      expect(db.prepare("SELECT id FROM projection_changes").all()).toEqual([]);
      expect(readMemorySourceChunks(db, "memory", value.entry.path)).toHaveLength(129);
      expect(
        db.prepare("SELECT hash FROM memory_index_sources WHERE path = ?").get(value.entry.path),
      ).toEqual({ hash: "second" });
    });
  });
});
