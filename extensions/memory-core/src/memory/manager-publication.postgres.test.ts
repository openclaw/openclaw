import fs from "node:fs";
import path from "node:path";
import type { DatabaseSync } from "node:sqlite";
import { getEnvironmentData, threadId } from "node:worker_threads";
import {
  admitStoreSearch,
  openEngineStore,
  withEngineStoreAdmission,
  type EngineConnection,
} from "openclaw/plugin-sdk/database-engine-worker-runtime";
import { isPostgresSqlConnection } from "openclaw/plugin-sdk/memory-core-host-engine-storage";
import { openNodeSqliteDatabase } from "openclaw/plugin-sdk/sqlite-worker-runtime";
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { MemoryIndexDatabase } from "./manager-database-context.js";
import {
  memoryEmbeddingCacheBatches,
  memoryPublicationBatches,
  memoryPublicationHeader,
  memoryPublicationInline,
} from "./manager-publication-transfer.js";
import { bindSqliteWorkerBackend } from "./manager-publication.worker.js";
import type { MemoryIndexMeta } from "./manager-reindex-state.js";
import { readMemoryDatabaseFacts } from "./manager-retrieval-read.js";
import { memoryTextSearchSchema } from "./manager-search-schema.js";
import type { MemorySourceIndexReplacement } from "./manager-source-index-kernel.js";

const configured: unknown = getEnvironmentData("openclaw.test.workboard.connection");
const connection = typeof configured === "string" ? configured : undefined;
const state = {
  vector: { enabled: true, available: true },
  fts: { enabled: true, available: true },
  hasVectorTable: true,
};
const metadata: MemoryIndexMeta = {
  provider: "fixture",
  model: "fixture",
  vectorDims: 3,
  chunkTokens: 400,
  chunkOverlap: 80,
};
const schema = `
CREATE TABLE memory_index_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path TEXT NOT NULL, source TEXT NOT NULL, hash TEXT NOT NULL,
  mtime DOUBLE PRECISION NOT NULL, size BIGINT NOT NULL, UNIQUE(path, source)
);
CREATE TABLE memory_index_chunks (
  chunk_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id TEXT NOT NULL UNIQUE, path TEXT NOT NULL, source TEXT NOT NULL,
  start_line BIGINT NOT NULL, end_line BIGINT NOT NULL, hash TEXT NOT NULL,
  model TEXT NOT NULL, text TEXT NOT NULL, embedding BYTEA NOT NULL, updated_at BIGINT NOT NULL
);
CREATE TABLE memory_index_chunk_recall_metadata (
  chunk_id TEXT PRIMARY KEY REFERENCES memory_index_chunks(id) ON DELETE CASCADE,
  importance BIGINT, triggers TEXT, project_key TEXT
);
CREATE TABLE memory_index_chunk_provenance (
  chunk_id TEXT PRIMARY KEY REFERENCES memory_index_chunks(id) ON DELETE CASCADE,
  origin_class TEXT NOT NULL, session_kind TEXT NOT NULL,
  observed_at BIGINT NOT NULL, supersedes_key TEXT
);
CREATE TABLE memory_index_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE memory_index_state (id BIGINT PRIMARY KEY, revision BIGINT NOT NULL);
INSERT INTO memory_index_state VALUES (1, 0);
CREATE TABLE memory_embedding_cache (
  provider TEXT NOT NULL, model TEXT NOT NULL, provider_key TEXT NOT NULL, hash TEXT NOT NULL,
  embedding BYTEA NOT NULL, dims BIGINT, updated_at BIGINT NOT NULL,
  PRIMARY KEY (provider, model, provider_key, hash)
);
`;

function replacement(name: string, text = `${name} searchable`): MemorySourceIndexReplacement {
  return {
    source: "memory",
    entry: { path: `memory/${name}.md`, hash: name, mtimeMs: 100.25, size: text.length },
    model: metadata.model,
    now: 100,
    vectorReady: true,
    embeddings: [[1, 0, 0]],
    chunks: [
      {
        startLine: 1,
        endLine: 1,
        hash: name,
        text,
        importance: 7,
        triggers: null,
        projectKey: null,
      },
    ],
  };
}

describe.skipIf(!connection)("PostgreSQL memory publication worker", () => {
  let root: string;
  let anchor: DatabaseSync;
  let database: EngineConnection;
  let namespace: string;
  let backend: ReturnType<typeof bindSqliteWorkerBackend>;
  let denyCommit = false;
  const admitted = <T>(operation: () => T) => withEngineStoreAdmission(operation);
  const pg = () => {
    if (!isPostgresSqlConnection(database)) {
      throw new Error("Expected PostgreSQL publication fixture");
    }
    return database;
  };
  const bind = (stageId?: string) =>
    bindSqliteWorkerBackend(
      { kind: "agent", stageId },
      {
        databasePath: path.join(root, "agent.sqlite"),
        database,
        admit(stage) {
          if (stage === "commit" && denyCommit) {
            throw new Error("publication authority revoked");
          }
        },
        admitSearchExtensions(definitions) {
          pg().runTransaction(() => {
            for (const [extension, definition] of Object.entries(definitions)) {
              admitStoreSearch(database, definition, { extension });
            }
          });
        },
      },
    );
  const open = () => {
    database = admitted(() =>
      openEngineStore({
        anchor,
        input: { connection: connection!, schemaPrefix: "memory_publication_test" },
        schema: { id: "memory_publication", version: 1, sqlite: "", postgres: schema },
        openSqlite: () => {
          throw new Error("Unexpected SQLite publication fixture");
        },
        prepareAnchor: () => {},
        inspectSqlite: () => ({ hasExistingData: false, hasEngineAnchor: false }),
      }),
    );
    backend = bind();
  };
  const admit = () => {
    pg().runTransaction(() => {
      admitStoreSearch(database, memoryTextSearchSchema("unicode61"), { extension: "memory.text" });
    });
    expect(
      backend.execute({ type: "vector.ensure", input: { dimensions: 3, state } }),
    ).toMatchObject({ ok: true });
  };
  const publishInline = (value: MemorySourceIndexReplacement) => {
    const inline = memoryPublicationInline(value);
    if (!inline) {
      throw new Error("Expected bounded inline fixture");
    }
    return backend.execute({ type: "source.replace.inline", input: { ...inline, state } });
  };
  const rows = () =>
    pg()
      .prepare(
        "SELECT c.path, c.text, v.embedding::text AS vector FROM memory_index_chunks c JOIN memory_index_chunks_vec v USING (id) ORDER BY c.path",
      )
      .all();
  const keyword = (term: string) =>
    pg()
      .prepare(
        "SELECT path FROM memory_index_chunks WHERE openclaw_search @@ plainto_tsquery('simple', ?) ORDER BY path",
      )
      .all(term);

  beforeAll(() => {
    expect(threadId, "Publication conformance uses one in-process admission descriptor").toBe(0);
    const artifacts = path.join(process.cwd(), ".artifacts");
    fs.mkdirSync(artifacts, { recursive: true });
    root = fs.mkdtempSync(path.join(artifacts, "memory-publication-postgres-"));
    anchor = openNodeSqliteDatabase(path.join(root, "anchor.sqlite"));
    open();
    namespace = admitted(() => String(pg().prepare("SELECT current_schema() AS name").get()!.name));
  });
  beforeEach(() =>
    admitted(() => {
      denyCommit = false;
      admit();
      pg().runTransaction(() =>
        pg().exec(
          "DELETE FROM memory_index_chunks; DELETE FROM memory_index_sources; DELETE FROM memory_index_meta; DELETE FROM memory_embedding_cache",
        ),
      );
    }),
  );
  afterEach(() =>
    admitted(() => {
      denyCommit = false;
      backend?.close();
      backend = bind();
    }),
  );
  afterAll(() => {
    admitted(() => {
      backend?.close();
      if (database?.isOpen) {
        pg().exec(`DROP SCHEMA "${namespace}" CASCADE`);
        database.close();
      }
    });
    anchor?.close();
    if (root) {
      fs.rmSync(root, { recursive: true, force: true });
    }
  });

  it("publishes inline and streamed sources, then re-admits their projections after restart", () =>
    admitted(() => {
      expect(publishInline(replacement("violet"))).toMatchObject({ ok: true, value: true });
      const large = replacement("orchid", `orchid ${"x".repeat(280_000)}`);
      const batches = [...memoryPublicationBatches(large)];
      expect(batches.length).toBeGreaterThan(1);
      backend.execute({ type: "stage.start", input: { header: memoryPublicationHeader(large) } });
      for (const fragments of batches) {
        backend.execute({ type: "stage.append", input: { fragments } });
      }
      expect(backend.execute({ type: "source.replace", input: { state } })).toMatchObject({
        ok: true,
        value: true,
      });
      expect(rows()).toEqual([
        { path: "memory/orchid.md", text: large.chunks[0]!.text, vector: "[1,0,0]" },
        { path: "memory/violet.md", text: "violet searchable", vector: "[1,0,0]" },
      ]);
      expect(keyword("violet")).toEqual([{ path: "memory/violet.md" }]);
      expect(keyword("orchid")).toEqual([{ path: "memory/orchid.md" }]);
      backend.close();
      database.close();
      open();
      admit();
      expect(rows()).toHaveLength(2);
      expect(keyword("orchid")).toEqual([{ path: "memory/orchid.md" }]);
    }));

  it("routes PostgreSQL indexing reads through the publication owner", async () => {
    const command = {
      type: "source.hash",
      input: { source: "memory", path: "memory/host-read.md" },
    } as const;
    const manager = new MemoryIndexDatabase(undefined, undefined, false, undefined, true, {
      engine: "postgres",
      hasIndex: true,
      ftsAvailable: true,
    });
    const dispatch = vi
      .spyOn(manager, "executePublication")
      .mockImplementation(async (received, assertCurrent) => {
        expect(received).toEqual(command);
        assertCurrent();
        return backend.execute(command);
      });
    try {
      const { result } = admitted(() => {
        expect(publishInline(replacement("host-read"))).toMatchObject({ ok: true });
        return {
          result: manager.read(command, () => {}),
        };
      });
      expect(await result).toBe("host-read");
    } finally {
      dispatch.mockRestore();
    }
  });

  it("atomically resets derived rows while retaining admitted search schema and revision", () =>
    admitted(() => {
      expect(publishInline(replacement("reset-me"))).toMatchObject({ ok: true });
      expect(backend.execute({ type: "index.writeMetadata", input: metadata })).toMatchObject({
        ok: true,
      });
      expect(
        backend.execute({
          type: "cache.write.inline",
          input: {
            header: {
              agentId: "main",
              provider: { id: "fixture", model: "fixture" },
              providerKey: "fixture-key",
            },
            entries: [{ hash: "reset-cache", embedding: [1, 0, 0] }],
          },
        }),
      ).toMatchObject({ ok: true, value: true });
      const before = readMemoryDatabaseFacts(database);
      denyCommit = true;
      expect(backend.execute({ type: "database.reset", input: undefined })).toMatchObject({
        ok: false,
        entered: true,
        committed: false,
        error: { message: "publication authority revoked" },
      });
      expect(keyword("reset")).toEqual([{ path: "memory/reset-me.md" }]);
      expect(rows()).toHaveLength(1);
      expect(backend.execute({ type: "index.facts", input: undefined })).toEqual(before);

      denyCommit = false;
      const reset = backend.execute({ type: "database.reset", input: undefined });
      expect(reset).toMatchObject({
        ok: true,
        value: true,
        facts: { meta: null, hasIndexedChunks: false, hasVectorTable: true },
      });
      expect(keyword("reset")).toEqual([]);
      expect(rows()).toEqual([]);
      expect(pg().prepare("SELECT hash FROM memory_embedding_cache").all()).toEqual([]);
      expect(pg().prepare("SELECT chunk_id FROM memory_index_chunk_recall_metadata").all()).toEqual(
        [],
      );
      expect(pg().prepare("SELECT chunk_id FROM memory_index_chunk_provenance").all()).toEqual([]);
      const after = readMemoryDatabaseFacts(database);
      expect(after.revision).toBeGreaterThan(before.revision);
      expect(backend.execute({ type: "database.reset", input: undefined })).toMatchObject({
        ok: true,
        value: false,
        facts: { revision: after.revision },
      });
      expect(publishInline(replacement("after-reset"))).toMatchObject({ ok: true });
      expect(keyword("reset")).toEqual([{ path: "memory/after-reset.md" }]);
      expect(rows()).toHaveLength(1);
    }));

  it("retains a private full reindex across short bindings and rolls back a refused commit", () =>
    admitted(() => {
      expect(publishInline(replacement("old"))).toMatchObject({ ok: true });
      expect(backend.execute({ type: "index.writeMetadata", input: metadata })).toMatchObject({
        ok: true,
      });
      const before = rows();
      const revision = Number(
        pg().prepare("SELECT revision FROM memory_index_state WHERE id = 1").get()!.revision,
      );
      const stageId = "full-reindex";
      const rebind = (id?: string) => {
        backend.close();
        backend = bind(id);
        expect(database.isTransaction).toBe(false);
      };
      rebind(stageId);
      expect(backend.execute({ type: "database.stage.start", input: undefined })).toMatchObject({
        ok: true,
      });
      rebind(stageId);
      const next = replacement("new", `new ${"replacement ".repeat(24_000)}`);
      const batches = [...memoryPublicationBatches(next)];
      expect(batches.length).toBeGreaterThan(1);
      backend.execute({ type: "stage.start", input: { header: memoryPublicationHeader(next) } });
      rebind(stageId);
      for (const fragments of batches) {
        backend.execute({ type: "stage.append", input: { fragments } });
        rebind(stageId);
        expect(rows()).toEqual(before);
      }
      expect(backend.execute({ type: "source.replace", input: { state } })).toMatchObject({
        ok: true,
      });
      rebind(stageId);
      expect(
        backend.execute({ type: "index.writeMetadata", input: { ...metadata, chunkTokens: 200 } }),
      ).toMatchObject({ ok: true });
      rebind();
      expect(rows()).toEqual(before);
      expect(keyword("new")).toEqual([]);
      expect(keyword("old")).toEqual([{ path: "memory/old.md" }]);
      denyCommit = true;
      expect(
        backend.execute({
          type: "database.stage.publish",
          input: { stageId, expectedRevision: revision, vectorIndexComplete: true },
        }),
      ).toMatchObject({
        ok: false,
        entered: true,
        committed: false,
        error: { message: "publication authority revoked" },
      });
      expect(rows()).toEqual(before);
      expect(keyword("old")).toEqual([{ path: "memory/old.md" }]);
      denyCommit = false;
      rebind();
      expect(
        backend.execute({
          type: "database.stage.publish",
          input: { stageId, expectedRevision: revision, vectorIndexComplete: true },
        }),
      ).toMatchObject({ ok: true });
      expect(rows()).toEqual([
        { path: "memory/new.md", text: next.chunks[0]!.text, vector: "[1,0,0]" },
      ]);
      expect(keyword("old")).toEqual([]);
      expect(keyword("new")).toEqual([{ path: "memory/new.md" }]);
      expect(backend.execute({ type: "index.facts", input: undefined })).toMatchObject({
        meta: { chunkTokens: 200 },
        vectorState: { state: "complete" },
      });
      backend.execute({ type: "database.stage.discard", input: { stageId } });
      expect(() =>
        backend.execute({
          type: "database.stage.publish",
          input: { stageId, expectedRevision: revision, vectorIndexComplete: true },
        }),
      ).toThrow("Memory reindex connection was lost");
      expect(rows()).toHaveLength(1);
    }));

  it("rejects a completed stage when another writer advances the canonical revision", () =>
    admitted(() => {
      expect(publishInline(replacement("current"))).toMatchObject({ ok: true });
      expect(backend.execute({ type: "index.writeMetadata", input: metadata })).toMatchObject({
        ok: true,
      });
      const before = rows();
      const revision = Number(
        pg().prepare("SELECT revision FROM memory_index_state WHERE id = 1").get()!.revision,
      );
      const stageId = "stale-reindex";
      backend.close();
      backend = bind(stageId);
      expect(backend.execute({ type: "database.stage.start", input: undefined })).toMatchObject({
        ok: true,
      });
      expect(publishInline(replacement("stale"))).toMatchObject({ ok: true });
      expect(backend.execute({ type: "index.writeMetadata", input: metadata })).toMatchObject({
        ok: true,
      });
      backend.close();
      backend = bind();
      pg().runTransaction(() =>
        pg().exec("UPDATE memory_index_state SET revision = revision + 1 WHERE id = 1"),
      );
      expect(
        backend.execute({
          type: "database.stage.publish",
          input: { stageId, expectedRevision: revision, vectorIndexComplete: true },
        }),
      ).toMatchObject({
        ok: false,
        entered: true,
        committed: false,
        error: { name: "MemoryIndexRevisionConflictError" },
      });
      expect(rows()).toEqual(before);
      expect(keyword("stale")).toEqual([]);
      backend.close();
      backend = bind();
      backend.execute({ type: "database.stage.discard", input: { stageId } });
    }));

  it("replays a multi-request cache through bounded connection-local staging", () =>
    admitted(() => {
      const entries = Array.from({ length: 40 }, (_, index) => ({
        hash: `cache-${index}`,
        embedding: Array.from({ length: 2048 }, () => 0.123456789),
      }));
      const batches = [...memoryEmbeddingCacheBatches(entries)];
      expect(batches.length).toBeGreaterThan(1);
      const queries = vi.spyOn(pg(), "query");
      let statements: string[];
      try {
        backend.execute({
          type: "cache.stage.start",
          input: {
            header: {
              agentId: "publication-fixture",
              provider: { id: "fixture", model: "fixture" },
              providerKey: "fixture",
            },
          },
        });
        for (const fragments of batches) {
          backend.execute({ type: "stage.append", input: { fragments } });
        }
        expect(backend.execute({ type: "cache.write", input: undefined })).toMatchObject({
          ok: true,
          value: true,
        });
      } finally {
        statements = queries.mock.calls.map(([sql]) => sql);
        queries.mockRestore();
      }
      expect(
        backend.execute({
          type: "cache.read",
          input: {
            providerIdentities: [{ provider: "fixture", model: "fixture", providerKey: "fixture" }],
            hashes: entries.map(({ hash }) => hash),
          },
        }),
      ).toEqual(new Map(entries.map(({ hash, embedding }) => [hash, embedding])));
      const reads = statements.filter((sql) =>
        sql.includes("SELECT ordinal, header, json, last FROM memory_stage_"),
      );
      expect(reads.length).toBeGreaterThan(1);
      expect(reads.every((sql) => sql.endsWith("ordinal > ? ORDER BY ordinal LIMIT 32"))).toBe(
        true,
      );
      expect(statements.some((sql) => /\bATTACH\b|shadow/iu.test(sql))).toBe(false);
    }));
});
