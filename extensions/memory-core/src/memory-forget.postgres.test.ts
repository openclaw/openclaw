import fs from "node:fs";
import path from "node:path";
import type { DatabaseSync } from "node:sqlite";
import { getEnvironmentData, threadId } from "node:worker_threads";
import {
  admitStoreSearch,
  openEngineStore,
  withEngineStoreAdmission,
  type EngineConnection,
} from "openclaw/plugin-sdk/database-engine-worker-runtime";
import {
  encodeMemoryEmbedding,
  isPostgresSqlConnection,
  readMemoryEntryOriginsInDatabase,
} from "openclaw/plugin-sdk/memory-core-host-engine-storage";
import { openNodeSqliteDatabase } from "openclaw/plugin-sdk/sqlite-worker-runtime";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { bindSqliteWorkerBackend } from "./memory-entry-origins.worker.js";
import { hasMemorySessionTombstone } from "./memory-session-tombstones.js";
import {
  memoryTextSearchSchema,
  memoryVectorSearchSchema,
} from "./memory/manager-search-schema.js";

const configured: unknown = getEnvironmentData("openclaw.test.workboard.connection");
const connection = typeof configured === "string" ? configured : undefined;
const schema = `
CREATE TABLE memory_index_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path TEXT NOT NULL, source TEXT NOT NULL
);
CREATE TABLE memory_index_chunks (
  chunk_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id TEXT NOT NULL UNIQUE, path TEXT NOT NULL, source TEXT NOT NULL,
  text TEXT NOT NULL, embedding BYTEA NOT NULL
);
CREATE TABLE memory_index_state (id BIGINT PRIMARY KEY, revision BIGINT NOT NULL);
INSERT INTO memory_index_state VALUES (1, 0);
CREATE TABLE memory_embedding_cache (hash TEXT PRIMARY KEY);
CREATE TABLE memory_entry_origins (
  entry_key TEXT NOT NULL, agent_id TEXT NOT NULL, session_id TEXT NOT NULL,
  session_key TEXT, origin_class TEXT NOT NULL, observed_at BIGINT NOT NULL,
  PRIMARY KEY (entry_key, agent_id, session_id)
);
CREATE TABLE memory_session_tombstones (
  session_id TEXT PRIMARY KEY, agent_id TEXT NOT NULL, reason TEXT NOT NULL, created_at BIGINT NOT NULL
);
`;

// This fixture isolates the forget owner's atomic commit from publication and search orchestration.
describe.skipIf(!connection)("PostgreSQL memory forget transaction", () => {
  let root: string;
  let anchor: DatabaseSync;
  let database: EngineConnection;
  let namespace: string;
  let backend: ReturnType<typeof bindSqliteWorkerBackend>;
  let denyCommit = false;
  const admitted = <T>(operation: () => T) => withEngineStoreAdmission(operation);
  const pg = () => {
    if (!isPostgresSqlConnection(database)) {
      throw new Error("Expected PostgreSQL forget fixture");
    }
    return database;
  };
  const open = () => {
    database = openEngineStore({
      anchor,
      input: { connection: connection!, schemaPrefix: "memory_forget_test" },
      schema: { id: "memory_forget", version: 1, sqlite: "", postgres: schema },
      openSqlite: () => {
        throw new Error("Unexpected SQLite forget fixture");
      },
      prepareAnchor: () => {},
      inspectSqlite: () => ({ hasExistingData: false, hasEngineAnchor: false }),
    });
    backend = bindSqliteWorkerBackend(
      { kind: "forget", prepareTombstones: true },
      {
        database,
        admit(stage) {
          if (stage === "commit" && denyCommit) {
            throw new Error("forget authority revoked");
          }
        },
      },
    );
  };
  const query = (sql: string) => pg().prepare(sql).all();
  const rows = (table: "memory_index_chunks" | "memory_index_chunks_vec") =>
    query(`SELECT id FROM ${table} ORDER BY id`);
  const revision = () =>
    Number(pg().prepare("SELECT revision FROM memory_index_state WHERE id = 1").get()!.revision);
  const expectProjection = (ids: string[], cached: boolean) => {
    for (const table of ["memory_index_chunks", "memory_index_chunks_vec"] as const) {
      expect(rows(table)).toEqual(ids.map((id) => ({ id })));
    }
    expect(query("SELECT path FROM memory_index_sources ORDER BY path")).toEqual(
      ids.map((id) => ({ path: id })),
    );
    expect(query("SELECT hash FROM memory_embedding_cache")).toEqual(
      cached ? [{ hash: "cached" }] : [],
    );
  };

  beforeAll(() => {
    expect(threadId, "Forget conformance uses one in-process admission descriptor").toBe(0);
    const artifacts = path.join(process.cwd(), ".artifacts");
    fs.mkdirSync(artifacts, { recursive: true });
    // openclaw-temp-dir: allow suite-owned PG anchor must survive the reopen assertion.
    root = fs.mkdtempSync(path.join(artifacts, "memory-forget-postgres-"));
    anchor = openNodeSqliteDatabase(path.join(root, "anchor.sqlite"));
    admitted(() => {
      open();
      namespace = String(pg().prepare("SELECT current_schema() AS name").get()!.name);
      pg().runTransaction(() => {
        admitStoreSearch(database, memoryTextSearchSchema("unicode61"), {
          extension: "memory.text",
        });
        admitStoreSearch(database, memoryVectorSearchSchema(3), { extension: "memory.vector" });
      });
    });
  });
  afterAll(() => {
    admitted(() => {
      backend?.close();
      if (database?.isOpen) {
        pg().exec(`DROP SCHEMA "${namespace}" CASCADE`);
        database.close();
      }
    });
    anchor?.close();
    if (root) {
      fs.rmSync(root, { recursive: true, force: true });
    }
  });

  it("rolls back every purge projection on denied commit and retains tombstones across re-admission", () =>
    admitted(() => {
      pg().runTransaction(() => {
        for (const id of ["target", "survivor"]) {
          pg()
            .prepare("INSERT INTO memory_index_sources(path, source) VALUES (?, 'memory')")
            .run(id);
          pg()
            .prepare(
              "INSERT INTO memory_index_chunks(id, path, source, text, embedding) VALUES (?, ?, 'memory', ?, ?)",
            )
            .run(id, id, `${id} searchable`, encodeMemoryEmbedding([1, 0, 0]));
        }
        pg().exec("INSERT INTO memory_embedding_cache VALUES ('cached')");
      });
      backend.execute({
        type: "record",
        input: {
          agentId: "main",
          origins: ["target", "survivor"].map((id) => ({
            entryKey: id,
            agentId: "main",
            sessionId: id,
            sessionKey: null,
            originClass: "owner",
            observedAt: 1,
          })),
        },
      });
      const lineage = {
        agentId: "main",
        sessionIds: ["target"],
        entryKeys: ["target"],
        identity: '[["target","target"]]',
      };
      const beforeRevision = revision();
      expect(backend.execute({ type: "forget.mark", input: lineage })).toEqual({ current: true });
      expect(revision()).toBe(beforeRevision + 1);
      const purge = {
        type: "forget.purge" as const,
        input: {
          ...lineage,
          chunkIds: ["target"],
          sources: [{ path: "target", source: "memory" }],
          hasVectorTable: true,
        },
      };
      denyCommit = true;
      expect(() => backend.execute(purge)).toThrow("forget authority revoked");
      expect(revision()).toBe(beforeRevision + 1);
      expectProjection(["survivor", "target"], true);
      expect(hasMemorySessionTombstone(database, "main", "target")).toBe(true);

      denyCommit = false;
      expect(backend.execute(purge)).toEqual({ current: true });
      expect(revision()).toBe(beforeRevision + 2);
      expectProjection(["survivor"], false);
      expect(
        query(
          "SELECT id FROM memory_index_chunks WHERE openclaw_search @@ plainto_tsquery('simple', 'target')",
        ),
      ).toEqual([]);
      expect(
        backend.execute({
          type: "delete",
          input: { agentId: "main", entryKeys: ["target"], sessionIds: ["target"] },
        }),
      ).toBe(1);
      backend.close();
      database.close();
      open();
      expect(revision()).toBe(beforeRevision + 2);
      expect(hasMemorySessionTombstone(database, "main", "target")).toBe(true);
      expect(readMemoryEntryOriginsInDatabase(database, { agentId: "main" })).toMatchObject([
        { entryKey: "survivor", sessionId: "survivor" },
      ]);
      expect(rows("memory_index_chunks_vec")).toEqual([{ id: "survivor" }]);
    }));
});
