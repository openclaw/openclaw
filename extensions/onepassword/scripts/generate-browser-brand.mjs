import { readFileSync, writeFileSync } from "node:fs";

// Embed the original marks unchanged: native plugin generations serve only JS/CSS.
const assets = {
  brandMark: "icon.png",
  brandLogoLight: "logo-iron-ore.png",
  brandLogoDark: "logo-white.png",
};
const lines = Object.entries(assets).map(([name, file]) => {
  const bytes = readFileSync(new URL(`../assets/${file}`, import.meta.url)).toString("base64");
  return `export const ${name} =\n  "data:image/png;base64,${bytes}";`;
});
writeFileSync(
  new URL("../browser/brand-mark.ts", import.meta.url),
  `// Generated by scripts/generate-browser-brand.mjs; do not edit.\n${lines.join("\n")}\n`,
);
