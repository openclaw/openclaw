import path from "node:path";
import { isRecord } from "openclaw/plugin-sdk/string-coerce-runtime";
import { parse, stringify, type TomlTable } from "smol-toml";

const INHERITED_TOP_LEVEL_CODEX_CONFIG_KEYS = new Set([
  "model",
  "model_provider",
  "model_reasoning_effort",
  "sandbox_mode",
]);

const INHERITED_MODEL_PROVIDER_CONFIG_KEYS = new Set([
  "name",
  "base_url",
  "wire_api",
  "env_key",
  "env_key_instructions",
  "requires_openai_auth",
  "request_max_retries",
  "stream_max_retries",
  "stream_idle_timeout_ms",
]);

export function renderIsolatedCodexConfig(params: {
  sourceConfigToml?: string;
  projectPaths: string[];
  mcpServers?: Record<string, unknown>;
}): string {
  let source: TomlTable = {};
  if (params.sourceConfigToml) {
    try {
      source = parse(params.sourceConfigToml, { integersAsBigInt: true });
    } catch {
      // Invalid source config cannot safely supply inherited project trust.
      throw new Error("Codex config.toml must be valid TOML before starting an ACP session.");
    }
  }
  const providers = new Map<string, Record<string, unknown>>();
  if (isRecord(source.model_providers)) {
    for (const [name, provider] of Object.entries(source.model_providers)) {
      if (!isRecord(provider)) {
        continue;
      }
      const config = Object.fromEntries(
        Object.entries(provider).filter(([key]) => INHERITED_MODEL_PROVIDER_CONFIG_KEYS.has(key)),
      );
      if (Object.keys(config).length) {
        providers.set(name, config);
      }
    }
  }
  const inherited = {
    ...Object.fromEntries(
      Object.entries(source).filter(([key]) => INHERITED_TOP_LEVEL_CODEX_CONFIG_KEYS.has(key)),
    ),
    ...(providers.size ? { model_providers: Object.fromEntries(providers) } : {}),
    ...(params.mcpServers ? { mcp_servers: params.mcpServers } : {}),
  };
  const trustedProjects = isRecord(source.projects)
    ? Object.entries(source.projects)
        .filter(([, project]) => isRecord(project) && project.trust_level === "trusted")
        .map(([projectPath]) => projectPath)
    : [];
  const projectPaths = Array.from(
    new Set(
      [...params.projectPaths, ...trustedProjects]
        .map((projectPath) => projectPath.trim())
        .filter(Boolean)
        .map((projectPath) => path.resolve(projectPath)),
    ),
  ).toSorted((left, right) => left.localeCompare(right));

  return [
    "# Generated by OpenClaw for Codex ACP sessions.",
    stringify(inherited, { numbersAsFloat: true }).trimEnd(),
    ...projectPaths.flatMap((projectPath) => [
      "",
      `[projects.${JSON.stringify(projectPath)}]`,
      'trust_level = "trusted"',
    ]),
    "",
  ]
    .filter((line, index, lines) => !(line === "" && lines[index - 1] === ""))
    .join("\n");
}
