import path from "node:path";
import { loadJsonFile, saveJsonFile } from "openclaw/plugin-sdk/json-store";
import { asNonArrayRecord, asNullableRecord } from "openclaw/plugin-sdk/string-coerce-runtime";
import {
  DEFAULT_OPENCLAW_BROWSER_COLOR,
  DEFAULT_OPENCLAW_BROWSER_PROFILE_NAME,
} from "./constants.js";

const CHROME_NETWORK_PREDICTION_DISABLED = 2;

function safeReadJson(filePath: string): Record<string, unknown> | null {
  return asNullableRecord(loadJsonFile(filePath));
}

function readNestedRecord(root: unknown, ...keys: string[]): Record<string, unknown> | null {
  let value = root;
  for (const key of keys) {
    value = asNullableRecord(value)?.[key];
  }
  return asNullableRecord(value);
}

function ensureNestedRecord(root: Record<string, unknown>, ...keys: string[]) {
  return keys.reduce((node, key) => (node[key] = asNonArrayRecord(node[key])), root);
}

function parseHexRgbToSignedArgbInt(hex: string): number | null {
  const cleaned = hex.trim().replace(/^#/, "");
  if (!/^[0-9a-fA-F]{6}$/.test(cleaned)) {
    return null;
  }
  const rgb = Number.parseInt(cleaned, 16);
  // Bitwise operations produce Chrome's signed 32-bit SkColor representation.
  return (0xff << 24) | rgb;
}

/** Return whether this profile was initialized with Chromium's automation keychain. */
export function usesOpenClawMockKeychain(userDataDir: string): boolean {
  const localState = safeReadJson(path.join(userDataDir, "Local State"));
  return (
    readNestedRecord(localState, "profile", "info_cache", "Default")?.openclaw_mock_keychain ===
    true
  );
}

/**
 * Prepare managed preferences before launch, preserving unrelated Chrome state.
 */
export function prepareOpenClawProfile(
  userDataDir: string,
  opts?: { name?: string; color?: string; downloadDir?: string; mockKeychain?: boolean },
) {
  const desiredName = opts?.name ?? DEFAULT_OPENCLAW_BROWSER_PROFILE_NAME;
  const desiredColor = (opts?.color ?? DEFAULT_OPENCLAW_BROWSER_COLOR).toUpperCase();
  const desiredColorInt = parseHexRgbToSignedArgbInt(desiredColor);

  const localStatePath = path.join(userDataDir, "Local State");
  const preferencesPath = path.join(userDataDir, "Default", "Preferences");

  const prefs = safeReadJson(preferencesPath) ?? {};
  // Chromium can preconnect before CDP Fetch interception. Write this before
  // cosmetic Local State so a decoration failure cannot skip the launch guard.
  ensureNestedRecord(prefs, "net").network_prediction_options = CHROME_NETWORK_PREDICTION_DISABLED;
  prefs.exit_type = "Normal";
  prefs.exited_cleanly = true;
  Object.assign(ensureNestedRecord(prefs, "profile"), {
    name: desiredName,
    profile_color: desiredColor,
    user_color: desiredColor,
  });
  if (desiredColorInt != null) {
    ensureNestedRecord(prefs, "autogenerated", "theme").color = desiredColorInt;
    ensureNestedRecord(prefs, "browser", "theme").user_color2 = desiredColorInt;
  }
  if (opts?.downloadDir) {
    Object.assign(ensureNestedRecord(prefs, "download"), {
      default_directory: opts.downloadDir,
      prompt_for_download: false,
      directory_upgrade: true,
    });
    ensureNestedRecord(prefs, "savefile").default_directory = opts.downloadDir;
  }
  saveJsonFile(preferencesPath, prefs);

  const localState = safeReadJson(localStatePath) ?? {};
  const profile = ensureNestedRecord(localState, "profile", "info_cache", "Default");
  Object.assign(profile, {
    name: desiredName,
    shortcut_name: desiredName,
    user_name: desiredName,
  });
  if (opts?.mockKeychain) {
    // Chrome preserves this key-source marker for later launches and cookie imports.
    profile.openclaw_mock_keychain = true;
  }
  Object.assign(profile, { profile_color: desiredColor, user_color: desiredColor });
  if (desiredColorInt != null) {
    Object.assign(profile, {
      profile_color_seed: desiredColorInt,
      profile_highlight_color: desiredColorInt,
      default_avatar_fill_color: desiredColorInt,
      default_avatar_stroke_color: desiredColorInt,
    });
  }
  saveJsonFile(localStatePath, localState);
}
