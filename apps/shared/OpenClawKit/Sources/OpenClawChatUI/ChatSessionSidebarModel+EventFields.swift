import Foundation

extension ChatSessionSidebarModel {
    /// Event rows omit catalog and lifecycle selection facts. Only present fields
    /// may change a retained incarnation; explicit nulls still clear their fields.
    static func mergingSessionFields(
        _ row: OpenClawChatSessionEntry,
        fields: Set<String>,
        into previous: OpenClawChatSessionEntry) -> OpenClawChatSessionEntry
    {
        var merged = previous
        func merge(_ field: String, _ path: WritableKeyPath<OpenClawChatSessionEntry, (some Any)?>) {
            if fields.contains(field) { merged[keyPath: path] = row[keyPath: path] }
        }
        merge("kind", \.kind)
        merge("displayName", \.displayName)
        merge("derivedTitle", \.derivedTitle)
        merge("lastMessagePreview", \.lastMessagePreview)
        merge("icon", \.icon)
        merge("channel", \.channel)
        merge("channelAvatarUrl", \.channelAvatarUrl)
        merge("origin", \.origin)
        merge("chatType", \.chatType)
        merge("groupChannel", \.groupChannel)
        merge("deliveryContext", \.deliveryContext)
        merge("owner", \.owner)
        merge("participants", \.participants)
        merge("expandedParticipants", \.expandedParticipants)
        merge("participantCount", \.participantCount)
        merge("visibility", \.visibility)
        merge("sharingRole", \.sharingRole)
        merge("hiddenFromInvolvingMe", \.hiddenFromInvolvingMe)
        merge("incognito", \.incognito)
        merge("archivedBy", \.archivedBy)
        merge("archiveReason", \.archiveReason)
        merge("projectId", \.projectId)
        merge("workspaceDir", \.workspaceDir)
        merge("spawnedWorkspaceDir", \.spawnedWorkspaceDir)
        merge("spawnedCwd", \.spawnedCwd)
        merge("repositoryWorkspaceId", \.repositoryWorkspaceId)
        merge("repository", \.repository)
        merge("execNode", \.execNode)
        merge("execCwd", \.execCwd)
        merge("forkedFromParent", \.forkedFromParent)
        merge("parentSessionId", \.parentSessionId)
        merge("controlOwnerSessionKey", \.controlOwnerSessionKey)
        merge("forkSource", \.forkSource)
        merge("previousSessionId", \.previousSessionId)
        merge("spawnDepth", \.spawnDepth)
        merge("subagentRole", \.subagentRole)
        merge("subagentControlScope", \.subagentControlScope)
        merge("placement", \.placement)
        merge("placementMove", \.placementMove)
        merge("classification", \.classification)
        merge("boardFace", \.boardFace)
        merge("agentId", \.agentId)
        merge("accountId", \.accountId)
        merge("peerKind", \.peerKind)
        merge("isMain", \.isMain)
        merge("isBackground", \.isBackground)
        merge("label", \.label)
        merge("autoLabel", \.autoLabel)
        merge("category", \.category)
        merge("color", \.color)
        merge("pinned", \.pinned)
        merge("pinnedAt", \.pinnedAt)
        merge("archived", \.archived)
        merge("archivedAt", \.archivedAt)
        merge("snoozedUntil", \.snoozedUntil)
        merge("snoozedAt", \.snoozedAt)
        merge("unread", \.unread)
        merge("agentStatus", \.agentStatus)
        merge("observerDigest", \.observerDigest)
        merge("surface", \.surface)
        merge("subject", \.subject)
        merge("room", \.room)
        merge("space", \.space)
        merge("createdAt", \.createdAt)
        merge("createdActor", \.createdActor)
        merge("createdVia", \.createdVia)
        merge("updatedAt", \.updatedAt)
        merge("lastReadAt", \.lastReadAt)
        merge("markedUnreadAt", \.markedUnreadAt)
        merge("lastInteractionAt", \.lastInteractionAt)
        merge("lastActivityAt", \.lastActivityAt)
        merge("sessionId", \.sessionId)
        merge("parentSessionKey", \.parentSessionKey)
        merge("spawnedBy", \.spawnedBy)
        merge("childSessions", \.childSessions)
        merge("status", \.status)
        merge("lastRunError", \.lastRunError)
        merge("hasActiveRun", \.hasActiveRun)
        merge("activeRunIds", \.activeRunIds)
        merge("hasActiveSubagentRun", \.hasActiveSubagentRun)
        merge("subagentRunState", \.subagentRunState)
        merge("swarmGroupId", \.swarmGroupId)
        merge("swarmPhase", \.swarmPhase)
        merge("swarmPhaseRank", \.swarmPhaseRank)
        merge("swarmLog", \.swarmLog)
        merge("worktree", \.worktree)
        merge("startedAt", \.startedAt)
        merge("endedAt", \.endedAt)
        merge("runtimeMs", \.runtimeMs)
        merge("agentRuntime", \.agentRuntime)
        merge("systemSent", \.systemSent)
        merge("abortedLastRun", \.abortedLastRun)
        merge("thinkingLevel", \.thinkingLevel)
        merge("reasoningLevel", \.reasoningLevel)
        merge("verboseLevel", \.verboseLevel)
        merge("fastMode", \.fastMode)
        merge("effectiveFastMode", \.effectiveFastMode)
        merge("permissionMode", \.permissionMode)
        merge("toolOverrides", \.toolOverrides)
        merge("inputTokens", \.inputTokens)
        merge("outputTokens", \.outputTokens)
        merge("totalTokens", \.totalTokens)
        merge("totalTokensFresh", \.totalTokensFresh)
        merge("modelProvider", \.modelProvider)
        merge("model", \.model)
        merge("contextTokens", \.contextTokens)
        // Capabilities belong to the selected model/runtime, not merely the key.
        if merged.model != previous.model || merged.modelProvider != previous.modelProvider ||
            merged.agentRuntime?.id != previous.agentRuntime?.id
        {
            merged.thinkingLevels = nil
            merged.thinkingOptions = nil
            merged.thinkingDefault = nil
        }
        merge("thinkingLevels", \.thinkingLevels)
        merge("thinkingOptions", \.thinkingOptions)
        merge("thinkingDefault", \.thinkingDefault)
        return merged
    }
}
