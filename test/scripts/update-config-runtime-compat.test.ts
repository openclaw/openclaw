import { spawnSync } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { afterEach, expect, it } from "vitest";
import { createNativeTypeScriptParser } from "../../scripts/lib/native-typescript.mts";
import { buildUpdateConfigRuntimeAlias } from "../../scripts/lib/update-config-runtime-compat.mts";
import {
  rewriteRootRuntimeImportsToStableAliases,
  writeStableRootRuntimeAliases,
} from "../../scripts/runtime-postbuild.mts";
import { createNodeEvalArgs, resolveTestNodeExecPath } from "../../src/test-utils/node-process.js";
import { useAutoCleanupTempDirTracker } from "../helpers/temp-dir.js";

const tempDirs = useAutoCleanupTempDirTracker(afterEach);
const node = resolveTestNodeExecPath();

/** Hard cap on reader subprocesses; a regressed alias must not fork a chain on a shared host. */
const MAX_READER_SUBPROCESS_DEPTH = 6;

type ReaderChainOutcome = {
  status: number | null;
  stderr: string;
  /** Reader subprocesses the alias forked, excluding the driver itself. */
  childCount: number;
  readCount: number;
  readPids: string[];
  readInDriver: boolean;
  errorCode: string | undefined;
};

async function readRecordedLines(file: string): Promise<string[]> {
  const content = await fs.readFile(file, "utf8").catch(() => "");
  return content.split("\n").filter((line) => line !== "");
}

function describeReaderChain(outcome: ReaderChainOutcome): string {
  return `children=${outcome.childCount} reads=${outcome.readCount} status=${outcome.status} error=${outcome.errorCode ?? "none"} readerPids=${outcome.readPids.join(",") || "none"}`;
}

/**
 * Drives the published config-read alias exactly as an update does and records the reader
 * subprocess chain through files, so an unbounded chain fails on a depth cap instead of hanging.
 */
async function runUpdateConfigReaderChain(options: {
  emulateBunQueryDrop: boolean;
}): Promise<ReaderChainOutcome> {
  const root = tempDirs.make("openclaw-update-config-reader-chain-");
  const dist = path.join(root, "dist");
  const readLog = path.join(root, "candidate-reads.log");
  const depthCounter = path.join(root, "reader-depth.txt");
  const depthLog = path.join(root, "reader-depth.log");
  const summaryFile = path.join(root, "reader-summary.json");
  await fs.mkdir(dist);
  await fs.writeFile(path.join(root, "package.json"), '{"type":"module"}');

  const candidateName = "io.runtime-Candidate.mjs";
  const candidatePath = path.join(dist, candidateName);
  const candidateSource = `import fs from "node:fs";
export function createConfigIO() {
  return {
    readBestEffortConfig: async () => {
      fs.appendFileSync(${JSON.stringify(readLog)}, process.pid + "\\n");
      return { pid: process.pid };
    },
    readConfigFileSnapshot: async () => ({ valid: true }),
    loadConfig: () => ({ pid: process.pid }),
  };
}
export async function readConfigFileSnapshot() { return { valid: true }; }
export function readCurrentConfigForPolicyCheck() { return { pid: process.pid }; }
`;
  await fs.writeFile(candidatePath, candidateSource);

  // The shipped alias, generated by its owner so the reader guard under test is the real one.
  const parser = createNativeTypeScriptParser({ cwd: root });
  try {
    await fs.writeFile(
      path.join(dist, "io.runtime.js"),
      buildUpdateConfigRuntimeAlias(
        candidateName,
        parser.parseSourceFile(candidatePath, candidateSource),
      ),
    );
  } finally {
    parser.close();
  }

  const hookDir = path.join(root, "hooks");
  await fs.mkdir(hookDir);
  // Bun 1.4.2 drops the reader query when the worker dynamically imports the alias, so the
  // reader re-evaluates the update guard and forks another reader. Reproduce that resolution.
  const dropReaderQueryHook = path.join(hookDir, "drop-reader-query.mjs");
  await fs.writeFile(
    dropReaderQueryHook,
    `import { registerHooks } from "node:module";
registerHooks({
  resolve(specifier, context, nextResolve) {
    const resolved = nextResolve(specifier, context);
    if (typeof resolved.url !== "string" || !resolved.url.includes("openclaw-config-read")) {
      return resolved;
    }
    const url = new URL(resolved.url);
    url.searchParams.delete("openclaw-config-read");
    return { ...resolved, url: url.href };
  },
});
`,
  );
  // Preloaded through NODE_OPTIONS so the cap also covers nested reader subprocesses.
  const readerDepthCapHook = path.join(hookDir, "reader-depth-cap.mjs");
  await fs.writeFile(
    readerDepthCapHook,
    `import fs from "node:fs";
const counter = ${JSON.stringify(depthCounter)};
const log = ${JSON.stringify(depthLog)};
const depth = fs.existsSync(counter) ? Number(fs.readFileSync(counter, "utf8")) : 0;
fs.writeFileSync(counter, String(depth + 1));
fs.appendFileSync(log, depth + "\\n");
if (depth >= ${MAX_READER_SUBPROCESS_DEPTH}) process.exit(97);
`,
  );

  const aliasUrl = pathToFileURL(path.join(dist, "io.runtime.js")).href;
  const driver = `
import fs from "node:fs";
const summaryFile = ${JSON.stringify(summaryFile)};
process.env.OPENCLAW_UPDATE_IN_PROGRESS = "1";
let summary;
try {
  const runtime = await import(${JSON.stringify(aliasUrl)});
  const value = await runtime.createConfigIO({ env: { ...process.env } }).readBestEffortConfig();
  summary = { ok: true, driverPid: process.pid };
} catch (error) {
  summary = { ok: false, driverPid: process.pid, errorCode: typeof error?.code === "string" ? error.code : undefined };
  process.exitCode = 1;
}
fs.writeFileSync(summaryFile, JSON.stringify(summary));
`;
  const hookImports = options.emulateBunQueryDrop
    ? [dropReaderQueryHook, readerDepthCapHook]
    : [readerDepthCapHook];
  const result = spawnSync(node, createNodeEvalArgs(driver), {
    cwd: path.dirname(root),
    encoding: "utf8",
    timeout: 60_000,
    env: {
      ...process.env,
      NODE_OPTIONS: hookImports.map((hook) => `--import ${pathToFileURL(hook).href}`).join(" "),
      NODE_DISABLE_COMPILE_CACHE: "1",
    },
  });

  const depths = await readRecordedLines(depthLog);
  const readPids = await readRecordedLines(readLog);
  const summaryText = await fs.readFile(summaryFile, "utf8").catch(() => "{}");
  const summary = JSON.parse(summaryText) as {
    ok: boolean;
    driverPid?: number;
    errorCode?: string;
  };
  return {
    status: result.status,
    stderr: result.stderr,
    childCount: Math.max(0, depths.length - 1),
    readCount: readPids.length,
    readPids,
    readInDriver: readPids.includes(String(summary.driverPid)),
    errorCode: summary.errorCode,
  };
}

it("reads candidate config after a package swap without reusing the driver's dependencies", async () => {
  const root = tempDirs.make("openclaw-update-config-runtime-");
  const dist = path.join(root, "dist");
  const dependency = path.join(root, "node_modules", "handoff-dependency");
  await fs.mkdir(dist);
  await fs.mkdir(dependency, { recursive: true });
  await fs.writeFile(path.join(root, "package.json"), '{"type":"module"}');
  await fs.writeFile(
    path.join(dependency, "package.json"),
    JSON.stringify({ type: "module", exports: { "./advanced": "./advanced.js" } }),
  );
  const dependencyFile = path.join(dependency, "advanced.js");
  await fs.writeFile(dependencyFile, "export const generation = 1;\n");
  await fs.writeFile(
    path.join(dist, "io.runtime-Candidate.mjs"),
    `import { probePathCaseInsensitiveSync } from "handoff-dependency/advanced";
export function createConfigIO(options = {}) {
  return {
    readBestEffortConfig: async () => ({
      generation: probePathCaseInsensitiveSync(),
      pid: process.pid,
      cwd: process.cwd(),
      selection: options.env?.OPENCLAW_CONFIG_PATH,
    }),
    readConfigFileSnapshot: async () => ({ valid: true, generation: probePathCaseInsensitiveSync() }),
    loadConfig: () => ({ generation: probePathCaseInsensitiveSync() }),
  };
}
export async function readConfigFileSnapshot() {
  return createConfigIO().readConfigFileSnapshot();
}
export function readCurrentConfigForPolicyCheck() {
  return createConfigIO().loadConfig();
}
export function normalRuntimeApi() { return process.pid; }
`,
  );
  const currentEntry = path.join(dist, "current-consumer.mjs");
  await fs.writeFile(
    currentEntry,
    'export { createConfigIO } from "./io.runtime-Candidate.mjs";\n',
  );
  rewriteRootRuntimeImportsToStableAliases({ rootDir: root });
  writeStableRootRuntimeAliases({ rootDir: root });
  await fs.writeFile(
    path.join(dist, "previous-runtime.mjs"),
    `import { generation } from "handoff-dependency/advanced";
     export function createConfigIO() {
       return { readBestEffortConfig: async () => ({ generation }) };
     }
     export async function readConfigFileSnapshot() { return { generation }; }`,
  );

  const script = `
import assert from "node:assert/strict";
import fs from "node:fs/promises";
const dependency = ${JSON.stringify(pathToFileURL(dependencyFile).href)};
const aliasPath = ${JSON.stringify(path.join(dist, "io.runtime.js"))};
const candidatePath = ${JSON.stringify(path.join(dist, "io.runtime-Candidate.mjs"))};
const aliasBytes = await fs.readFile(aliasPath);
const candidateBytes = await fs.readFile(candidatePath);
const driverDependency = await import(dependency);
assert.equal(driverDependency.generation, 1);
await fs.writeFile(new URL(dependency), "export const generation = 2; export function probePathCaseInsensitiveSync() { return generation; }\\n");
process.env.OPENCLAW_UPDATE_IN_PROGRESS = "1";
const runtime = await import(${JSON.stringify(pathToFileURL(path.join(dist, "io.runtime.js")).href)});
const io = runtime.createConfigIO({ env: { ...process.env, OPENCLAW_CONFIG_PATH: "synthetic-config-selection" } });
const result = await io.readBestEffortConfig();
assert.equal(result.generation, 2);
assert.notEqual(result.pid, process.pid);
assert.equal(result.cwd, ${JSON.stringify(root)});
assert.equal(result.selection, "synthetic-config-selection");
assert.equal((await runtime.readConfigFileSnapshot()).generation, 2);
assert.equal((await io.readConfigFileSnapshot()).valid, true);
assert.equal(io.loadConfig().generation, 2);
assert.equal(runtime.readCurrentConfigForPolicyCheck().generation, 2);
assert.equal((await import(dependency)).generation, 1);
await fs.unlink(new URL(dependency));
const fallback = await io.readBestEffortConfig().catch(error => {
  assert.equal(error.code, "candidate-config-read-failed");
  return {};
});
assert.deepEqual(fallback, {});
await fs.writeFile(new URL(dependency), "export const generation = 1;\\n");
await fs.writeFile(aliasPath, 'export * from "./previous-runtime.mjs";');
await fs.unlink(candidatePath);
assert.equal((await io.readBestEffortConfig()).generation, 1);
assert.equal((await runtime.readConfigFileSnapshot()).generation, 1);
await fs.writeFile(candidatePath, candidateBytes);
await fs.writeFile(aliasPath, aliasBytes);
await fs.writeFile(new URL(dependency), "export function probePathCaseInsensitiveSync() { return 2; }\\n");
assert.equal((await io.readBestEffortConfig()).generation, 2);
`;
  const result = spawnSync(node, ["--input-type=module", "--eval", script], {
    cwd: path.dirname(root),
    encoding: "utf8",
    timeout: 30_000,
    env: { ...process.env, NODE_OPTIONS: "", NODE_DISABLE_COMPILE_CACHE: "1" },
  });
  expect(result.stderr).toContain("[update:warning:candidate-config-read-failed]");
  expect(result.status).toBe(0);

  for (const { marker, entry } of [
    { marker: "0", entry: path.join(dist, "io.runtime.js") },
    { marker: "1", entry: currentEntry },
  ]) {
    const normal = spawnSync(
      node,
      [
        "--input-type=module",
        "--eval",
        `import assert from "node:assert/strict";
       const runtime = await import(${JSON.stringify(pathToFileURL(entry).href)});
       const result = await runtime.createConfigIO().readBestEffortConfig();
       assert.equal(result.generation, 2);
       if (${JSON.stringify(marker)} === "0") {
         assert.equal(runtime.normalRuntimeApi(), process.pid);
         assert.equal(result.pid, process.pid);
       } else {
         assert.notEqual(result.pid, process.pid);
       }`,
      ],
      {
        encoding: "utf8",
        timeout: 30_000,
        env: {
          ...process.env,
          NODE_OPTIONS: "",
          NODE_DISABLE_COMPILE_CACHE: "1",
          OPENCLAW_UPDATE_IN_PROGRESS: marker,
        },
      },
    );
    expect(normal.stderr).toBe("");
    expect(normal.status).toBe(0);
  }
});

it("reads the candidate config in exactly one reader subprocess on Node", async () => {
  const outcome = await runUpdateConfigReaderChain({ emulateBunQueryDrop: false });
  expect(outcome, describeReaderChain(outcome)).toMatchObject({
    status: 0,
    childCount: 1,
    readCount: 1,
    readInDriver: false,
    errorCode: undefined,
  });
  expect(outcome.stderr).toBe("");
});

it("reads the candidate config in one reader when the runtime drops the reader query", async () => {
  const outcome = await runUpdateConfigReaderChain({ emulateBunQueryDrop: true });
  expect(outcome, describeReaderChain(outcome)).toMatchObject({
    status: 0,
    childCount: 1,
    readCount: 1,
    readInDriver: false,
    errorCode: undefined,
  });
  expect(outcome.stderr).toBe("");
});
