/// Look up the required scope for a method name.
#[must_use]
pub fn scope_for(method: &str) -> Option<Scope> {
    CORE_METHODS
        .iter()
        .find(|spec| spec.name == method)
        .map(|spec| spec.scope)
}

/// Whether a method is part of the canonical core table.
#[must_use]
pub fn is_core_method(method: &str) -> bool {
    scope_for(method).is_some()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_covers_the_core_surface_without_duplicates() {
        assert!(CORE_METHODS.len() >= 400, "only {}", CORE_METHODS.len());
        let mut names: Vec<&str> = CORE_METHODS.iter().map(|s| s.name).collect();
        names.sort_unstable();
        let before = names.len();
        names.dedup();
        assert_eq!(before, names.len(), "duplicate method names");
    }

    #[test]
    fn scopes_resolve_for_known_methods() {
        assert_eq!(scope_for("health"), Some(Scope::Read));
        assert_eq!(scope_for("config.set"), Some(Scope::Admin));
        assert_eq!(scope_for("no.such.method"), None);
    }
}

