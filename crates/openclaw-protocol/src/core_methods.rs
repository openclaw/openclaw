/// Required operator scope for a Gateway method.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Scope {
    /// Read-only operator access.
    Read,
    /// Write access to sessions, config, and state.
    Write,
    /// Administrative access: channel lifecycle, exec approvals, plugins.
    Admin,
    /// A specific operator scope (pairing, approvals, talk, ...).
    Named(&'static str),
}

impl Scope {
    /// Wire name of this scope, matching `docs/gateway/operator-scopes.md`.
    #[must_use]
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Read => "operator.read",
            Self::Write => "operator.write",
            Self::Admin => "operator.admin",
            Self::Named(name) => name,
        }
    }
}

/// One entry in the canonical method table.
#[derive(Debug, Clone, Copy)]
pub struct MethodSpec {
    /// Wire method name.
    pub name: &'static str,
    /// Minimum operator scope required.
    pub scope: Scope,
}

